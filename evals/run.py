"""Run the evals: `uv run python -m evals.run` writes evals/results.md from the local cache."""

from pathlib import Path

import pandas as pd

from evals.cases import CASES, answer
from wise_mcp.analysis import WellbeingData
from wise_mcp.config import DATAFLOWS
from wise_mcp.store import DataStore

OUT = Path(__file__).with_name("results.md")


def raw_data(store: DataStore) -> pd.DataFrame:
    """The database as downloaded: every dataflow, every row, codes only."""
    return pd.concat([store.observations(name) for name in DATAFLOWS], ignore_index=True)


def report(store: DataStore) -> str:
    raw, data = raw_data(store), WellbeingData.from_store(store)
    fetched = store.status().fetched_at
    lines = [
        "# Evals: naive analysis vs wise_mcp",
        "",
        "Each question answered twice from the same OECD data: by a naive first pass with pandas "
        "(filter to the measure code, compute the obvious thing), and by wise_mcp's analysis "
        "functions, which the MCP tools call. Where How's Life? 2024 publishes the figure, it is "
        "shown too. Generated by `uv run python -m evals.run`"
        + (f" from data fetched {fetched:%Y-%m-%d}." if fetched else "."),
        "",
    ]
    lines += [
        "## Against the OECD's published figures",
        "",
        "| Question | Published | Naive | Error | wise_mcp | Error |",
        "|---|---|---|---|---|---|",
    ]
    for case in (c for c in CASES if c.published_value is not None):
        cells = []
        for value in (_number(answer(case.naive, raw, data)), _number(answer(case.wise, data))):
            cells += (
                ["–", "–"]
                if value is None
                else [f"{value:.2f}", _error(value, case.published_value)]
            )
        lines.append(f"| {case.question} | {case.published_value:.1f} | {' | '.join(cells)} |")
    lines += ["", "## Every question", ""]
    for number, case in enumerate(CASES, 1):
        lines += [
            f"### {number}. {case.question}",
            "",
            f"- **Naive:** {answer(case.naive, raw, data)}",
            f"- **wise_mcp:** {answer(case.wise, data)}",
        ]
        if case.published:
            lines.append(f"- **How's Life? 2024:** {case.published}")
        lines += [f"- **Why they differ:** {case.pitfall}", ""]
    return "\n".join(lines)


def _number(text: str) -> float | None:
    """The leading number of an answer ("80.55 (OECD, 2022)" -> 80.55), if it has one."""
    try:
        return float(text.split()[0].replace(",", ""))
    except ValueError:
        return None


def _error(value: float, published: float) -> str:
    return f"{(value - published) / published:+.1%}"


def main() -> None:
    OUT.write_text(report(DataStore()))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
